    /// A directory of this run's own, since the tests share a process.
    fn scratch(name: &str) -> PathBuf {
        let path = std::env::temp_dir().join(format!("corbel-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(&path).expect("a writable temp directory");
        path
    }

    /// What [`Source::open`] made of a file with these contents.
    fn opened(name: &str, contents: &[u8]) -> Result<Source> {
        let path = scratch(name).join("input");
        fs::write(&path, contents).expect("seed the input");
        Source::open(&path)
    }

    /// The evidence a line carries, one shape at a time. A slicer's own
    /// preamble is comments; a start G-code is commands, most of which this
    /// tool never acts on and so reads as `Code::Other`.
    #[test]
    fn a_line_reads_as_gcode_when_it_is_a_command_or_a_comment() {
        for line in [
            "; generated by PrusaSlicer 2.8.1",
            ";FLAVOR:Marlin",
            ";TYPE:Perimeter",
            "G1 X20.000 Y0.000 E0.66000",
            "M83",
            "G28 ; home",
            "M104 S210",
            "T0",
            "N7 G1 X1",
        ] {
            assert!(reads_as_gcode(line), "{line}");
        }

        // An ASCII STL and a Wavefront OBJ, which are what a mistyped path
        // most often lands on that has no zero byte to give it away.
        for line in [
            "solid cube",
            "facet normal 0 0 -1",
            "vertex 0 0 0",
            "endsolid cube",
            "v 0.0 1.0 2.0",
            "# a comment in some other language",
            "",
        ] {
            assert!(!reads_as_gcode(line), "{line}");
        }
    }

    /// A slicer hands over the only copy of a file it has, and the default
    /// output target is that file, so anything unrecognisable stops the run
    /// before a sink is ever opened.
    #[test]
    fn a_file_that_is_not_gcode_is_refused_by_name() {
        let zipped = b"PK\x03\x04\x14\x00\x00\x00\x08\x00 a 3mf is a zip";
        let Err(error) = opened("zip", zipped) else {
            panic!("a zip was taken for G-code");
        };
        assert!(error.to_string().contains("zero byte"), "{error}");

        let Err(error) = opened("stl", b"solid cube\nvertex 0 0 0\nendsolid cube\n") else {
            panic!("an ASCII STL was taken for G-code");
        };
        assert!(
            error.to_string().contains("no command or comment"),
            "{error}"
        );

        let Err(error) = opened("empty", b"") else {
            panic!("an empty file was taken for G-code");
        };
        assert!(error.to_string().contains("empty"), "{error}");
    }

    /// The evidence only has to arrive once, and a slicer's file opens with
    /// it. A comment carrying bytes that are not UTF-8 still counts: slicers
    /// copy object names in the host's encoding, and refusing those would
