//! Post-processes sliced G-code with two independent transforms.
//!
//! [`brick`] raises every other internal perimeter loop by half a layer
//! height, staggering the seams between loops so that layers interlock instead
//! of stacking as independent flat sheets — which is where FDM prints are
//! weakest — and draws the visible wall a few microns toward the material
//! behind it so the joint against it closes without the part growing.
//!
//! [`zaa`] follows the model's surface *within* a layer, varying the height of
//! an extrusion by up to half a layer either way so that a shallow top comes
//! out as a ramp rather than a staircase.
//!
//! Either, or both: they own different regions of the print, so composing them
//! costs one pass over the file rather than two.
//!
//! It streams: G-code arrives a line at a time from a [`Source`] and leaves a
//! line at a time through a [`Sink`], so a file is never held in memory.

