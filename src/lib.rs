    /// A slicer runs its post-processor over a file in the system temp
    /// directory, where every local user may create a name. `O_EXCL` is what
    /// says a name someone else got to first is an error rather than a file of
    /// theirs being truncated and filled with this print.
    #[cfg(unix)]
    #[test]
    fn a_temporary_is_never_opened_through_a_name_that_already_exists() {
        let directory = scratch("exclusive");
        let theirs = directory.join("their-secret");
        fs::write(&theirs, "not ours\n").expect("seed their file");
        let planted = directory.join("part.gcode.1234.tmp");
        std::os::unix::fs::symlink(&theirs, &planted).expect("plant the symlink");

        let error = create_exclusively(&planted, 0o600).expect_err("the name is taken");
        assert_eq!(error.kind(), io::ErrorKind::AlreadyExists);
        assert_eq!(
            fs::read_to_string(&theirs).expect("read back"),
            "not ours\n"
        );
        assert!(
            fs::symlink_metadata(&planted).is_ok(),
            "the link was removed"
        );
    }

    /// Refusing a taken name is only half of it: the name also has to be one
    /// nobody can take in advance, which the process id alone is not.
    #[test]
    fn a_temporary_takes_a_name_that_cannot_be_worked_out_in_advance() {
        use std::collections::HashSet;

        let target = Path::new("/spool/prints/part.gcode");
        let names: HashSet<PathBuf> = (0..64).map(|_| temporary_path(target)).collect();
        assert_eq!(names.len(), 64, "two runs drew the same name");

        let predictable = format!(".{}.tmp", std::process::id());
        for path in &names {
            assert_eq!(path.parent(), target.parent(), "{path:?}");
            let name = path.file_name().unwrap_or_default().to_string_lossy();
            assert!(name.starts_with("part.gcode."), "{name}");
            assert!(name.ends_with(".tmp"), "{name}");
            assert!(!name.ends_with(&predictable), "{name}");
        }
    }

    /// `File::create` applies `0666 & umask` and narrows afterwards, which
    /// leaves a window where another user can open the temporary — and an fd
    /// opened in that window keeps reading as the file is written.
    #[cfg(unix)]
    #[test]
    fn a_temporary_is_created_with_the_permissions_it_will_keep() {
        use std::os::unix::fs::PermissionsExt;

        let directory = scratch("private");
        let mode = |path: &Path| fs::metadata(path).expect("stat").permissions().mode() & 0o777;

        // The creating call itself, with nothing done afterwards: no group or
        // other bits exist at any point.
        let private = directory.join("private.tmp");
        let file = create_exclusively(&private, 0o600).expect("create");
        drop(file);
        assert_eq!(mode(&private) & 0o077, 0, "created readable by others");

        // And a target that is readable by others gets a temporary that is
        // too, whatever the umask narrowed it to on the way in.
        let target = directory.join("part.gcode");
        fs::write(&target, "G1 X1\n").expect("seed the target");
        fs::set_permissions(&target, fs::Permissions::from_mode(0o644)).expect("chmod");
        let (_, temporary) =
            create_temporary(&target, intended_mode([target.as_path()])).expect("temporary");
        assert_eq!(mode(&temporary), 0o644);
    }

    /// `rename` replaces a symbolic link itself, not the file it stands for,
    /// so a slicer directory pointed at shared storage would keep the
    /// unprocessed G-code and lose the link.
    #[cfg(unix)]
    #[test]
    fn a_symlinked_target_is_followed_to_the_file_it_stands_for() {
        let directory = scratch("symlink");
        let real = directory.join("real.gcode");
        let link = directory.join("part.gcode");
        fs::write(&real, "G1 X1\n").expect("seed the target");
        std::os::unix::fs::symlink(&real, &link).expect("link it");

        let source = Source::open(&link).expect("open");
        let mut sink = source.sink(&link).expect("sink");
        sink.write_all(b"G1 X2\n").expect("write");
        sink.commit().expect("commit");

        assert_eq!(fs::read_to_string(&real).expect("read back"), "G1 X2\n");
        let kind = fs::symlink_metadata(&link).expect("stat").file_type();
        assert!(kind.is_symlink(), "the link was replaced by a regular file");
        assert_eq!(fs::read_link(&link).expect("read the link"), real);
    }

    /// A rename publishes a new inode, so the other names for the old one keep
    /// the file as it was sliced. Nothing in `std` can move them, so it is
    /// said rather than done quietly.
    #[cfg(unix)]
    #[test]
    fn replacing_a_file_says_what_it_cannot_carry_over() {
        let directory = scratch("hard-links");
        let target = directory.join("part.gcode");
        fs::write(&target, "G1 X1\n").expect("seed the target");

        let source = Source::open(&target).expect("open");
        let quiet = source.sink(&target).expect("sink");
        assert!(quiet.warnings().is_empty(), "{:?}", quiet.warnings());
        drop(quiet);

        fs::hard_link(&target, directory.join("also.gcode")).expect("hard link");
        let sink = source.sink(&target).expect("sink");
        let warning = sink.warnings().join("\n");
        assert!(warning.contains("hard-linked"), "{warning}");
        assert!(warning.contains("part.gcode"), "{warning}");
    }

    /// Every reader here strips a trailing `\r` and every transform writes a
    /// bare `\n`, so putting the file's own ending back is the only thing that
    /// keeps a Windows-authored file byte-identical where nothing was changed.
    #[test]
    fn a_rewrite_puts_back_the_line_endings_the_file_arrived_with() {
        for (label, original) in [
            ("endings-lf", "G1 X1\nG1 X2\n"),
            ("endings-crlf", "G1 X1\r\nG1 X2\r\n"),
            ("endings-lf-open", "G1 X1\nG1 X2"),
            ("endings-crlf-open", "G1 X1\r\nG1 X2"),
        ] {
            let input = scratch(label).join("in.gcode");
            fs::write(&input, original).expect("seed the input");

            let source = Source::open(&input).expect("open");
            let mut sink = source.sink(&input).expect("sink");
            // What a transform does: one line at a time, terminated with a
            // bare newline whatever the file used.
            for line in original.lines() {
                writeln!(sink, "{line}").expect("write");
            }
            sink.commit().expect("commit");

            assert_eq!(
                fs::read_to_string(&input).expect("read back"),
                original,
                "{label}"
            );
        }
    }

    #[test]
    fn a_source_can_be_read_twice_and_written_somewhere_else() {
        let directory = scratch("rewrite");
        let input = directory.join("in.gcode");
        let output = directory.join("out.gcode");
        fs::write(&input, "; layer_height = 0.2\nG1 Z0.2\nG1 Z0.4\n").expect("seed the input");

        let source = Source::open(&input).expect("open");
        assert!(!source.is_binary());
        let survey = source.survey().expect("survey");
        assert_eq!(survey.layers, 2);

        let sink = source.sink(&output).expect("sink");
        let copied = source
            .rewrite(sink, |mut reader, writer| {
                let count = io::copy(&mut reader, writer)?;
                Ok(count)
            })
            .expect("rewrite");

        assert_eq!(
            copied as usize,
            fs::metadata(&input).expect("stat").len() as usize
        );
        assert_eq!(
            fs::read_to_string(&output).expect("read back"),
            fs::read_to_string(&input).expect("read the input")
        );
    }
