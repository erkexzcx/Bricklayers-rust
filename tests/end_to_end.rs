    let help = String::from_utf8_lossy(&output.stdout);

    for heading in ["Bricklayering:", "Z anti-aliasing:"] {
        assert!(help.contains(heading), "{heading} missing from:\n{help}");
    }
    let bricks = help.find("Bricklayering:").expect("a heading");
